# 支持用户自定义词典
_CUSTOM = os.path.join(os.path.dirname(os.path.abspath(__file__)), "custom_words.txt")
if os.path.exists(_CUSTOM):
    try:
        with open(_CUSTOM, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                parts = [p.strip() for p in line.split("\t")]
                if len(parts) >= 2 and parts[1] in ("pos", "neg"):
                    word, polarity = parts[0], parts[1]
                    weight = float(parts[2]) if len(parts) >= 3 and parts[2] else 1.0
                    if polarity == "pos":
                        POSITIVE[word] = weight
                    else:
                        NEGATIVE[word] = weight
    except Exception:
        pass

